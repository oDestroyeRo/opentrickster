#!/usr/bin/env node
// PROTOTYPE tool. Reads tokens.json, writes tokens.css for the prototype and
// TOKENS.md for the GPUI handoff, refreshes the token tables in the repository's
// DESIGN.md when that file is present, and exits 1 when a contrast or line-height check fails.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));
const themes = Object.keys(tokens.semantic);

function resolve(value) {
  const m = /^\{([\w-]+)\.([\w-]+)\}([0-9A-Fa-f]{2})?$/.exec(value);
  if (!m) return value.toUpperCase();
  const base = tokens.primitive[m[1]]?.[m[2]];
  if (!base) throw new Error(`Unknown primitive ${m[1]}.${m[2]}`);
  return (base + (m[3] ?? '')).toUpperCase();
}

const resolved = Object.fromEntries(
  themes.map((t) => [t, Object.fromEntries(Object.entries(tokens.semantic[t]).map(([k, v]) => [k, resolve(v)]))]),
);

const channel = (hex, i) => parseInt(hex.slice(1 + i * 2, 3 + i * 2), 16) / 255;
const linear = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const luminance = (hex) => {
  const [r, g, b] = [0, 1, 2].map((i) => linear(channel(hex, i)));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};
const gpui = (hex) => (hex.length === 9 ? `rgba(0x${hex.slice(1)})` : `rgb(0x${hex.slice(1)})`);
const cssName = (k) => `--${k.replaceAll('.', '-')}`;

const css = ['/* GENERATED by build-tokens.mjs from tokens.json. Do not edit. */'];
for (const t of themes) {
  css.push(`:root[data-theme="${t}"] {`, `  color-scheme: ${t};`);
  for (const [k, v] of Object.entries(resolved[t])) css.push(`  ${cssName(k)}: ${v};`);
  css.push('}');
}
const { type, space, radius, size, motion } = tokens;
css.push(':root {');
css.push(`  --font-ui: "${type['family.ui'].split(', ').join('", "')}", -apple-system, system-ui, sans-serif;`);
css.push(`  --font-mono: "${type['family.mono']}", ui-monospace, Menlo, monospace;`);
for (const [k, v] of Object.entries(type)) {
  if (k.startsWith('weight.')) css.push(`  ${cssName(k)}: ${v};`);
  if (k.startsWith('size.')) css.push(`  ${cssName('fs.' + k.slice(5))}: ${v[0]}px;`, `  ${cssName('lh.' + k.slice(5))}: ${v[1]}px;`);
}
for (const [k, v] of Object.entries(space)) css.push(`  --space-${k}: ${v}px;`);
for (const [k, v] of Object.entries(radius)) css.push(`  --radius-${k}: ${v}px;`);
for (const [k, v] of Object.entries(size)) css.push(`  ${cssName('size.' + k)}: ${v}px;`);
for (const [k, v] of Object.entries(motion)) css.push(`  ${cssName('motion.' + k)}: ${v};`);
css.push('}');
writeFileSync(join(here, 'tokens.css'), css.join('\n') + '\n');

const checks = [];
for (const t of themes) {
  for (const c of tokens.contrast) {
    const fg = resolved[t][c.fg];
    const bg = resolved[t][c.bg];
    const r = ratio(fg.slice(0, 7), bg.slice(0, 7));
    checks.push({ theme: t, ...c, fgHex: fg, bgHex: bg, r, pass: r >= c.min });
  }
}

const h = (level, text) => `${'#'.repeat(level)} ${text}`;
const tables = (level) => {
const md = [
  h(level, 'Semantic colors'),
  '',
  `| Token | ${themes.map((t) => `${t} hex | ${t} GPUI`).join(' | ')} |`,
  `| --- | ${themes.map(() => '--- | ---').join(' | ')} |`,
];
for (const k of Object.keys(resolved[themes[0]])) {
  md.push(`| \`${k}\` | ${themes.map((t) => `\`${resolved[t][k]}\` | \`${gpui(resolved[t][k])}\``).join(' | ')} |`);
}
md.push('', h(level, 'Contrast checks'), '', 'WCAG 2 contrast ratio of each pair. Text needs 4.5, graphics and control boundaries need 3.', '');
md.push('| Theme | Foreground | Background | Use | Ratio | Minimum | Result |', '| --- | --- | --- | --- | --- | --- | --- |');
for (const c of checks) {
  md.push(`| ${c.theme} | \`${c.fg}\` | \`${c.bg}\` | ${c.use} | ${c.r.toFixed(2)} | ${c.min} | ${c.pass ? 'pass' : 'FAIL'} |`);
}
md.push('', h(level, 'Type scale'), '', `UI family is ${type['family.ui']}. Mono family is ${type['family.mono']}, used only for build identifiers and map coordinates.`, '');
md.push(`Every line height is at least ${type['line.min']} times its size, and \`node build-tokens.mjs\` fails otherwise. Thai stacks vowels and tone marks above and below the baseline. Measured in Chrome with IBM Plex Sans Thai, the cluster ปู่ needs 1.46 times its size to fit inside a line box that centers it.`, '');
md.push('| Role | Size px | Line height px | Ratio | GPUI |', '| --- | --- | --- | --- | --- |');
for (const [k, v] of Object.entries(type)) {
  if (k.startsWith('size.')) md.push(`| ${k.slice(5)} | ${v[0]} | ${v[1]} | ${(v[1] / v[0]).toFixed(2)} | \`.text_size(px(${v[0]}.)).line_height(px(${v[1]}.))\` |`);
}
md.push('', h(level, 'Space, radius, and size'), '', '| Token | Value px |', '| --- | --- |');
for (const [k, v] of Object.entries(space)) md.push(`| space.${k} | ${v} |`);
for (const [k, v] of Object.entries(radius)) md.push(`| radius.${k} | ${v} |`);
for (const [k, v] of Object.entries(size)) md.push(`| size.${k} | ${v} |`);
md.push('', h(level, 'Motion'), '', '| Token | Value |', '| --- | --- |');
for (const [k, v] of Object.entries(motion)) md.push(`| motion.${k} | \`${v}\` |`);
return md.join('\n');
};
writeFileSync(join(here, 'TOKENS.md'), [
  '# Prototype tokens',
  '',
  'Generated by `node build-tokens.mjs` from `tokens.json`. Do not edit by hand.',
  'The GPUI column is the literal to pass to `gpui::rgb` or `gpui::rgba`.',
  '',
  tables(2),
].join('\n') + '\n');

const design = join(here, '..', '..', 'DESIGN.md');
const [open, close] = ['<!-- tokens:start -->', '<!-- tokens:end -->'];
if (existsSync(design)) {
  const doc = readFileSync(design, 'utf8');
  const a = doc.indexOf(open), b = doc.indexOf(close);
  if (a < 0 || b < a) throw new Error(`DESIGN.md needs the ${open} and ${close} markers`);
  writeFileSync(design, `${doc.slice(0, a + open.length)}\n\n${tables(4)}\n\n${doc.slice(b)}`);
  console.log('refreshed the token tables in DESIGN.md');
}

const failed = checks.filter((c) => !c.pass);
for (const c of checks) {
  console.log(`${c.pass ? 'pass' : 'FAIL'}  ${c.theme.padEnd(5)} ${c.fg.padEnd(16)} on ${c.bg.padEnd(15)} ${c.r.toFixed(2).padStart(5)} (min ${c.min})`);
}
console.log(failed.length ? `${failed.length} contrast check(s) failed` : `all ${checks.length} contrast checks pass`);
const tight = Object.entries(type).filter(([k, v]) => k.startsWith('size.') && v[1] / v[0] < type['line.min']);
for (const [k, v] of tight) console.log(`FAIL  ${k} line height ${v[1]} is under ${type['line.min']} times ${v[0]}`);
console.log(tight.length ? `${tight.length} type size(s) too tight` : `all type sizes keep line height at ${type['line.min']} times the size or more`);
process.exit(failed.length || tight.length ? 1 : 0);
